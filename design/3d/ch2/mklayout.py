"""layout.json -> layout.js (window.LAYOUT = ...) so level.html opens by double-click (file://).
Run after editing layout.json: python3 3d/ch2/mklayout.py"""
import json, os
here = os.path.dirname(os.path.abspath(__file__))
data = json.load(open(os.path.join(here, "layout.json")))
open(os.path.join(here, "layout.js"), "w").write("// generated by mklayout.py from layout.json, edit that file instead\nwindow.LAYOUT = " + json.dumps(data) + ";\n")
print("layout.js written,", len(data["islands"]), "islands")
