"""Embed every review .glb as base64 JS (window.GLB[name]) so design/3d/index.html opens by double-click.
Run after each export: python3 design/3d/tools/embed.py"""
import base64, glob, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
for glb in sorted(glob.glob(os.path.join(root, "*", "*.glb"))):
    if os.sep + "poc" + os.sep in glb:
        continue
    name = os.path.splitext(os.path.basename(glb))[0]
    data = base64.b64encode(open(glb, "rb").read()).decode()
    open(glb + ".js", "w").write(f'// generated by tools/embed.py from {name}.glb\n(window.GLB=window.GLB||{{}})["{name}"]="{data}";\n')
    print("embedded", os.path.relpath(glb, root), len(data) // 1024, "KB")
